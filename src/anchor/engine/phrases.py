#: Length used when nothing else is configured (SPEC 7.2, confirmed by owner).
DEFAULT_PHRASE_LENGTH: Final = 150


def generate_phrase(length: int = DEFAULT_PHRASE_LENGTH) -> str:
    """Return a fresh phrase of at least ``length`` characters.

    Words are drawn with :mod:`secrets`, so the result cannot be predicted from
    an earlier one, and the phrase is never shortened below the requested
    length: the effort is the whole point.
    """
    if length <= 0:
        raise ValueError("phrase length must be positive")

    words: list[str] = []
    total = 0
    while total < length:
        word = secrets.choice(_WORDS)
        words.append(word)
        total += len(word) + (1 if len(words) > 1 else 0)
    return " ".join(words)


def phrase_matches(expected: str, typed: str | None) -> bool:
    """Compare a typed phrase with the generated one.

    Leading and trailing whitespace is forgiven, because a terminal or a text
    entry adds it for reasons that have nothing to do with the user's resolve.
    Everything else must match exactly.
    """
    if typed is None:
        return False
    return secrets.compare_digest(expected.strip(), typed.strip())
